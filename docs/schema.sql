CREATE TABLE memories(id TEXT PRIMARY KEY,text TEXT NOT NULL,source TEXT NOT NULL,date TEXT NOT NULL,type TEXT NOT NULL,sensitivity TEXT NOT NULL,status TEXT NOT NULL,project TEXT NOT NULL,reference TEXT NOT NULL);

CREATE TABLE documents(id TEXT PRIMARY KEY,hash TEXT UNIQUE NOT NULL,name TEXT NOT NULL,career TEXT NOT NULL,path TEXT NOT NULL,pages INTEGER NOT NULL,date TEXT NOT NULL);

CREATE TABLE chunks(id TEXT PRIMARY KEY,document_id TEXT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,page INTEGER NOT NULL,text TEXT NOT NULL,hash TEXT NOT NULL);

CREATE VIRTUAL TABLE search USING fts5(id UNINDEXED,kind UNINDEXED,text,tokenize='unicode61 remove_diacritics 2');

CREATE TABLE vectors(id TEXT PRIMARY KEY,model TEXT NOT NULL,values_json TEXT NOT NULL);

CREATE TABLE edges(id TEXT PRIMARY KEY,origin TEXT NOT NULL,target TEXT NOT NULL,relation TEXT NOT NULL,source TEXT NOT NULL,status TEXT NOT NULL);

CREATE TABLE tasks(id TEXT PRIMARY KEY,objective TEXT NOT NULL,agent TEXT NOT NULL,status TEXT NOT NULL,created TEXT NOT NULL,updated TEXT NOT NULL,attempts INTEGER NOT NULL DEFAULT 0,checkpoint TEXT NOT NULL DEFAULT '{}',result TEXT,error TEXT,deadline_seconds INTEGER NOT NULL DEFAULT 120);

CREATE TABLE events(id INTEGER PRIMARY KEY AUTOINCREMENT,task_id TEXT,at TEXT NOT NULL,state TEXT NOT NULL,message TEXT NOT NULL);
